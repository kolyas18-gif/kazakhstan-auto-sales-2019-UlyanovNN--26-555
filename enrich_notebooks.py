def enrich():
    for filename, rules in NOTES.items():
        path = ROOT / filename
        nb = nbformat.read(path, 4)
        nb.cells = [c for c in nb.cells if not c.metadata.get('reviewed_interpretation')]
        cells = []
        for cell in nb.cells:
            cells.append(cell)
            if cell.cell_type == 'code':
                for marker, text in rules.items():
                    if marker in cell.source:
                        note = nbformat.v4.new_markdown_cell('**Интерпретация.** ' + text)
                        note.metadata['reviewed_interpretation'] = True
                        cells.append(note)
        nb.cells = cells
        nbformat.validate(nb)
        nbformat.write(nb, path)


if __name__ == '__main__':
    enrich()
